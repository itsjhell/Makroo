def _rebuild_key(ev):
    if "name" in ev:
        try:
            return keyboard.Key[ev["name"]]
        except KeyError:
            return None
    if ev.get("vk") is not None:
        return keyboard.KeyCode.from_vk(ev["vk"])
    if ev.get("char"):
        return keyboard.KeyCode.from_char(ev["char"])
    return None


class MacroPlayer:
    def __init__(self):
        self._stop = threading.Event()
        self._thread = None
        self.current_loop = 0

    @property
    def running(self):
        return self._thread is not None and self._thread.is_alive()

    def start(self, events, speed, count):
        """count=None -> infinite loop. speed: multiplier (2 = double speed)."""
        if self.running or not events:
            return
        self._stop.clear()
        self.current_loop = 0
        self._thread = threading.Thread(
            target=self._run, args=(list(events), max(0.01, speed), count), daemon=True
        )
        self._thread.start()

    def stop(self):
        self._stop.set()

    def _run(self, events, speed, count):
        kctrl = keyboard.Controller()
        mctrl = mouse.Controller()
        pressed_keys = set()
        pressed_btns = set()
        loop = 0
        try:
            while not self._stop.is_set() and (count is None or loop < count):
                loop += 1
                self.current_loop = loop
                start = time.perf_counter()
                for ev in events:
                    target = ev["t"] / speed
                    while True:
                        wait = target - (time.perf_counter() - start)
                        if wait <= 0:
                            break
                        if self._stop.wait(min(wait, 0.05)):
                            return
                    if self._stop.is_set():
                        return
                    self._exec(ev, kctrl, mctrl, pressed_keys, pressed_btns)
        finally:
            # release anything still held down (avoids "stuck" keys)
            for k in pressed_keys:
                try:
                    kctrl.release(k)
                except Exception:
                    pass
            for b in pressed_btns:
                try:
                    mctrl.release(b)
                except Exception:
                    pass

    def _exec(self, ev, kctrl, mctrl, pressed_keys, pressed_btns):
        try:
            e = ev["e"]
            if e == "kd":
                key = _rebuild_key(ev)
                if key is not None:
                    kctrl.press(key)
                    pressed_keys.add(key)
            elif e == "ku":
                key = _rebuild_key(ev)
                if key is not None:
                    kctrl.release(key)
                    pressed_keys.discard(key)
            elif e == "mm":
                mctrl.position = (ev["x"], ev["y"])
            elif e == "md":
                btn = mouse.Button[ev["btn"]]
                mctrl.position = (ev["x"], ev["y"])
                mctrl.press(btn)
                pressed_btns.add(btn)
            elif e == "mu":
                btn = mouse.Button[ev["btn"]]
                mctrl.position = (ev["x"], ev["y"])
                mctrl.release(btn)
                pressed_btns.discard(btn)
            elif e == "ms":
                mctrl.position = (ev["x"], ev["y"])
                mctrl.scroll(ev["dx"], ev["dy"])
        except Exception:
            pass


