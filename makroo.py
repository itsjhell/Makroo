def resource_path(name):
    """Path of a bundled resource (works both from source and PyInstaller)."""
    base = getattr(sys, "_MEIPASS", os.path.dirname(os.path.abspath(__file__)))
    return os.path.join(base, name)

# Windows flags marking events generated by software (i.e. by us):
# we ignore them so our own synthetic clicks/keys never trigger hotkeys
# or get recorded into macros.
LLKHF_INJECTED = 0x10  # keyboard
LLMHF_INJECTED = 0x01  # mouse


def _kb_filter(msg, data):
    """Low-level keyboard filter: drop injected events."""
    return not (data.flags & LLKHF_INJECTED)


def _ms_filter(msg, data):
    """Low-level mouse filter: drop injected events."""
    return not (data.flags & LLMHF_INJECTED)


# ---------------------------------------------------------------------------
# Hotkeys: serializable representation of a key or mouse button
# ---------------------------------------------------------------------------

def key_to_spec(key):
    """Convert a pynput key into a serializable dict."""
    if isinstance(key, keyboard.Key):
        return {"kind": "key", "name": key.name}
    vk = getattr(key, "vk", None)
    ch = getattr(key, "char", None)
    spec = {"kind": "key"}
    if vk is not None:
        spec["vk"] = vk
    if ch:
        spec["char"] = ch.lower()
    return spec


def button_to_spec(button):
    return {"kind": "mouse", "button": button.name}


def spec_match(a, b):
    if not a or not b or a.get("kind") != b.get("kind"):
        return False
    if a["kind"] == "mouse":
        return a.get("button") == b.get("button")
    if "name" in a or "name" in b:
        return a.get("name") == b.get("name")
    if a.get("vk") is not None and b.get("vk") is not None:
        return a["vk"] == b["vk"]
    return a.get("char") is not None and a.get("char") == b.get("char")


def spec_id(spec):
    return json.dumps(spec, sort_keys=True) if spec else ""


def spec_label(spec):
    """Human-readable hotkey name."""
    if not spec:
        return "—"
    if spec["kind"] == "mouse":
        names = {
            "left": "Left Mouse",
            "right": "Right Mouse",
            "middle": "Middle Mouse",
            "x1": "Mouse 4 (X1)",
            "x2": "Mouse 5 (X2)",
        }
        return names.get(spec["button"], "Mouse " + spec["button"])
    if "name" in spec:
        return spec["name"].replace("_", " ").upper()
    if spec.get("char"):
        return spec["char"].upper()
    return "VK %s" % spec.get("vk")


# ---------------------------------------------------------------------------
# Global hotkey manager (keyboard + mouse, always listening)
# ---------------------------------------------------------------------------

class HotkeyManager:
    def __init__(self):
        self._bindings = []          # list of (spec, callback)
        self._down = set()           # anti auto-repeat
        self._lock = threading.Lock()
        self.enabled = True
        self._kb = keyboard.Listener(
            on_press=self._on_press,
            on_release=self._on_release,
            win32_event_filter=_kb_filter,
        )
        self._ms = mouse.Listener(
            on_click=self._on_click,
            win32_event_filter=_ms_filter,
        )
        self._kb.start()
        self._ms.start()

    def set_bindings(self, bindings):
        """Replace all bindings with a list of (spec, callback)."""
        with self._lock:
            self._bindings = list(bindings)

    def matches_any(self, spec):
        """True if the spec matches any registered hotkey."""
        with self._lock:
            return any(spec_match(s, spec) for s, _ in self._bindings)

    def _fire(self, spec):
        if not self.enabled:
            return
        with self._lock:
            targets = []
            for s, cb in self._bindings:
                if spec_match(s, spec) and cb not in targets:
                    targets.append(cb)
        for cb in targets:
            try:
                cb()
            except Exception:
                pass

    def _on_press(self, key):
        spec = key_to_spec(key)
        sid = spec_id(spec)
        if sid in self._down:
            return  # Windows key auto-repeat: ignore
        self._down.add(sid)
        self._fire(spec)

    def _on_release(self, key):
        self._down.discard(spec_id(key_to_spec(key)))

    def _on_click(self, x, y, button, pressed):
        if pressed:
            self._fire(button_to_spec(button))


