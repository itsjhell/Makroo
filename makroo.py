class AutoClicker:
    def __init__(self):
        self._stop = threading.Event()
        self._thread = None
        self.clicks_done = 0

    @property
    def running(self):
        return self._thread is not None and self._thread.is_alive()

    def start(self, interval_s, button, clicks_per_action, count, position):
        """count=None -> infinite; position=None -> current cursor."""
        if self.running:
            return
        self._stop.clear()
        self.clicks_done = 0
        self._thread = threading.Thread(
            target=self._run,
            args=(max(0.001, interval_s), button, clicks_per_action, count, position),
            daemon=True,
        )
        self._thread.start()

    def stop(self):
        self._stop.set()

    def _run(self, interval, button, clicks, count, position):
        ctrl = mouse.Controller()
        done = 0
        while not self._stop.is_set():
            if position is not None:
                ctrl.position = position
            ctrl.click(button, clicks)
            done += 1
            self.clicks_done = done
            if count is not None and done >= count:
                break
            if self._stop.wait(interval):
                break


