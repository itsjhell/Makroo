class HotkeyCapture:
    """Opens a small window and captures the first key/button pressed."""

    def __init__(self, app, on_done):
        self.app = app
        self.on_done = on_done
        self.result = None
        self._got = threading.Event()

        app.hotkeys.enabled = False  # don't trigger hotkeys while capturing

        self.top = tk.Toplevel(app.root)
        self.top.title("Set hotkey")
        self.top.attributes("-topmost", True)
        self.top.resizable(False, False)
        self.top.grab_set()
        ttk.Label(
            self.top,
            text="Press a key or a mouse button...\n(ESC to cancel)",
            padding=20,
            justify="center",
        ).pack()
        self.top.protocol("WM_DELETE_WINDOW", self._cancel)

        self._kb = keyboard.Listener(on_press=self._on_key, win32_event_filter=_kb_filter)
        self._ms = mouse.Listener(on_click=self._on_click, win32_event_filter=_ms_filter)
        # small delay so we don't capture the click that opened the dialog
        app.root.after(150, self._start_listeners)
        self._poll()

    def _start_listeners(self):
        self._kb.start()
        self._ms.start()

    def _on_key(self, key):
        if key == keyboard.Key.esc:
            self.result = None
        else:
            self.result = key_to_spec(key)
        self._got.set()

    def _on_click(self, x, y, button, pressed):
        if pressed:
            self.result = button_to_spec(button)
            self._got.set()

    def _poll(self):
        if self._got.is_set():
            self._finish()
        else:
            self.top.after(50, self._poll)

    def _cancel(self):
        self.result = None
        self._finish()

    def _finish(self):
        for lst in (self._kb, self._ms):
            try:
                lst.stop()
            except Exception:
                pass
        self.top.grab_release()
        self.top.destroy()
        self.app.hotkeys.enabled = True
        if self.result is not None:
            self.on_done(self.result)


