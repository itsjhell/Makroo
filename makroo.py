    # ------------------------- generic hotkey rows --------------------------

    def _hotkey_row(self, parent, row, label, cfg_path):
        section, key = cfg_path
        ttk.Label(parent, text=label).grid(row=row, column=0, sticky="w",
                                           pady=2)
        btn = ttk.Button(parent, text=spec_label(self.cfg[section][key]),
                         width=18)
        btn.grid(row=row, column=1, padx=6, pady=2, sticky="w")

        def change():
            def done(spec):
                self.cfg[section][key] = spec
                btn.config(text=spec_label(spec))
                self._rebind_hotkeys()
            HotkeyCapture(self, done)

        btn.config(command=change)
        parent.grid_columnconfigure(1, weight=0)
        return btn

    def _rebind_hotkeys(self):
        """Rebuild the binding list. When start and stop share the same key,
        register a single toggle binding (registering both would fire the
        callback twice on one keypress: start then immediately stop)."""
        a, m = self.cfg["autoclicker"], self.cfg["macro"]
        bindings = []

        if spec_match(a["hk_start"], a["hk_stop"]):
            bindings.append((a["hk_start"], self._hk_ac_toggle))
        else:
            bindings.append((a["hk_start"], self._hk_ac_start))
            bindings.append((a["hk_stop"], self._hk_ac_stop))

        if spec_match(m["hk_rec"], m["hk_rec_stop"]):
            bindings.append((m["hk_rec"], self._hk_rec_toggle))
        else:
            bindings.append((m["hk_rec"], self._hk_rec_start))
            bindings.append((m["hk_rec_stop"], self._hk_rec_stop))

        if spec_match(m["hk_play"], m["hk_play_stop"]):
            bindings.append((m["hk_play"], self._hk_play_toggle))
        else:
            bindings.append((m["hk_play"], self._hk_play_start))
            bindings.append((m["hk_play_stop"], self._hk_play_stop))

        self.hotkeys.set_bindings(bindings)

    # hotkey callbacks (run on the listener thread; no direct tk access).
    # Each one is gated on the active tab, so autoclicker and macro hotkeys
    # are mutually exclusive and may share the same keys.

    def _hk_ac_toggle(self):
        if self.active_mode != "auto":
            return
        if self.clicker.running:
            self.clicker.stop()
        else:
            self.ac_start()

    def _hk_ac_start(self):
        if self.active_mode == "auto":
            self.ac_start()

    def _hk_ac_stop(self):
        if self.active_mode == "auto":
            self.clicker.stop()

    def _hk_rec_toggle(self):
        if self.active_mode != "macro":
            return
        if self.recorder.recording:
            self._rec_stop()
        else:
            self._rec_start()

    def _hk_rec_start(self):
        if self.active_mode == "macro":
            self._rec_start()

    def _hk_rec_stop(self):
        if self.active_mode == "macro":
            self._rec_stop()

    def _hk_play_toggle(self):
        if self.active_mode != "macro":
            return
        if self.player.running:
            self.player.stop()
        else:
            self._play_start()

    def _hk_play_start(self):
        if self.active_mode == "macro":
            self._play_start()

    def _hk_play_stop(self):
        if self.active_mode == "macro":
            self.player.stop()

    # ------------------------ shared start/stop logic -----------------------

    def _rec_start(self):
        if self.recorder.recording or self.player.running:
            return
        self.recorder.start(bool(self.mc_moves.get()))

    def _rec_stop(self):
        if not self.recorder.recording:
            return
        self.macro_events = self.recorder.stop()
        self.macro_name = None

    def _play_start(self):
        if self.player.running or self.recorder.recording or not self.macro_events:
            return
        count = None
        if self.mc_repeat_mode.get() == "n":
            count = max(1, int(self._get_float(self.mc_repeat_count, 1)))
        self.player.start(self.macro_events, self._speed_factor(), count)

    # --------------------------- autoclicker actions ------------------------

    def ac_start(self):
        if self.clicker.running:
            return
        interval = self._get_float(self.ac_interval, 100) * \
            UNIT_SECONDS.get(self.ac_unit.get(), 0.001)
        button = mouse.Button.left if self.ac_button.get() == "Left" \
            else mouse.Button.right
        clicks = 2 if self.ac_click_type.get() == "Double" else 1
        count = None
        if self.ac_repeat_mode.get() == "n":
            count = max(1, int(self._get_float(self.ac_repeat_count, 100)))
        position = None
        if self.ac_pos_mode.get() == "fixed":
            position = (int(self._get_float(self.ac_x, 0)),
                        int(self._get_float(self.ac_y, 0)))
        self.clicker.start(interval, button, clicks, count, position)

    def ac_stop(self):
        self.clicker.stop()

    def _update_pos_state(self):
        state = "normal" if self.ac_pos_mode.get() == "fixed" else "disabled"
        for w in (self.ac_x_entry, self.ac_y_entry, self.ac_pick_btn):
            w.config(state=state)

    def _pick_position(self):
        """The next physical click sets the coordinates."""
        if self._pick_listener is not None:
            return
        self.statusbar.config(text="Click anywhere on the screen to set "
                                   "the coordinates…")
        self.hotkeys.enabled = False
        self._pick_result = None

        def on_click(x, y, button, pressed):
            if pressed:
                self._pick_result = (int(x), int(y))
                return False  # stop the listener

        self._pick_listener = mouse.Listener(on_click=on_click,
                                             win32_event_filter=_ms_filter)
        self._pick_listener.start()

    # ------------------------------ macro actions ---------------------------

    def mc_record_toggle(self):
        if self.recorder.recording:
            self._rec_stop()
        else:
            self._rec_start()

    def mc_play_toggle(self):
        if self.player.running:
            self.player.stop()
        else:
            self._play_start()
            if not self.macro_events:
                messagebox.showinfo(APP_NAME,
                                    "No macro in memory.\n"
                                    "Record a macro or load one from file.")

    def _speed_factor(self):
        choice = self.mc_speed.get()
        if choice == "Custom":
            return max(0.01, self._get_float(self.mc_speed_custom, 1.0))
        try:
            return float(choice.rstrip("x"))
        except ValueError:
            return 1.0

    def _update_speed_state(self):
        state = "normal" if self.mc_speed.get() == "Custom" else "disabled"
        self.mc_speed_entry.config(state=state)

    def mc_save(self):
        if not self.macro_events:
            messagebox.showinfo(APP_NAME, "No macro to save.")
            return
        path = filedialog.asksaveasfilename(
            title="Save macro",
            defaultextension=".json",
            filetypes=[("Makroo macro", "*.json")],
            initialdir=APP_DIR,
        )
        if not path:
            return
        try:
            with open(path, "w", encoding="utf-8") as f:
                json.dump({"app": APP_NAME, "version": 1,
                           "events": self.macro_events}, f)
            self.macro_name = os.path.basename(path)
            self.statusbar.config(text=f"Macro saved: {self.macro_name}")
        except OSError as exc:
            messagebox.showerror(APP_NAME, f"Error while saving:\n{exc}")

    def mc_load(self):
        path = filedialog.askopenfilename(
            title="Load macro",
            filetypes=[("Makroo macro", "*.json"), ("All files", "*.*")],
            initialdir=APP_DIR,
        )
        if not path:
            return
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            events = data.get("events")
            if not isinstance(events, list) or not events:
                raise ValueError("invalid or empty macro file")
            self.macro_events = events
            self.macro_name = os.path.basename(path)
            self.statusbar.config(text=f"Macro loaded: {self.macro_name} "
                                       f"({len(events)} events)")
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            messagebox.showerror(APP_NAME, f"Could not load the macro:\n{exc}")

    # ------------------------------ UI polling ------------------------------

    def _poll(self):
        # live mouse position
        try:
            x, y = mouse.Controller().position
            self.mouse_pos_label.config(text=f"Cursor: {int(x)}, {int(y)}")
        except Exception:
            pass

        # "pick point" result
        if self._pick_listener is not None and not self._pick_listener.running:
            self._pick_listener = None
            self.hotkeys.enabled = True
            if self._pick_result:
                self.ac_x.set(str(self._pick_result[0]))
                self.ac_y.set(str(self._pick_result[1]))
                self.statusbar.config(
                    text=f"Coordinates set: {self._pick_result[0]}, "
                         f"{self._pick_result[1]}")

        # autoclicker state
        if self.clicker.running:
            self.ac_status.config(
                text=f"● RUNNING — clicks done: "
                     f"{self.clicker.clicks_done}", foreground="#c00000")
            self.ac_start_btn.config(state="disabled")
            self.ac_stop_btn.config(state="normal")
        else:
            done = self.clicker.clicks_done
            self.ac_status.config(
                text="Ready" if not done else f"Stopped — last run: {done} clicks",
                foreground="#006000" if not done else "black")
            self.ac_start_btn.config(state="normal")
            self.ac_stop_btn.config(state="disabled")

        # macro state
        if self.recorder.recording:
            self.mc_status.config(
                text=f"⏺ RECORDING… ({len(self.recorder.events)} events)",
                foreground="#c00000")
            self.mc_rec_btn.config(text="⏹  Stop recording")
            self.mc_play_btn.config(state="disabled")
        elif self.player.running:
            self.mc_status.config(
                text=f"▶ PLAYING… (loop {self.player.current_loop})",
                foreground="#0050c0")
            self.mc_rec_btn.config(text="⏺  Record", state="disabled")
            self.mc_play_btn.config(text="⏹  Stop playback", state="normal")
        else:
            n = len(self.macro_events)
            name = f" — {self.macro_name}" if self.macro_name else ""
            self.mc_status.config(
                text=f"Macro in memory: {n} events{name}" if n
                else "No macro in memory",
                foreground="black")
            self.mc_rec_btn.config(text="⏺  Record", state="normal")
            self.mc_play_btn.config(text="▶  Play", state="normal")

        self._update_speed_state()
        self.root.after(100, self._poll)

    # ------------------------------ misc ------------------------------------

    def _on_tab_changed(self, _event=None):
        try:
            idx = self.notebook.index(self.notebook.select())
        except Exception:
            return
        self.active_mode = "auto" if idx == 0 else "macro"

    def _apply_topmost(self):
        self.root.attributes("-topmost", bool(self.topmost_var.get()))

    def _on_close(self):
        self.clicker.stop()
        self.player.stop()
        if self.recorder.recording:
            self.recorder.stop()
        self._save_config()
        self.root.destroy()

    def run(self):
        self.root.mainloop()


