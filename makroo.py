    # ----------------------------- config ---------------------------------

    def _load_config(self):
        try:
            with open(CONFIG_PATH, "r", encoding="utf-8") as f:
                cfg = _deep_merge(DEFAULT_CONFIG, json.load(f))
        except Exception:
            return json.loads(json.dumps(DEFAULT_CONFIG))
        # migrate values written by the old Italian UI
        a = cfg["autoclicker"]
        for field in ("interval_unit", "button", "click_type"):
            a[field] = _MIGRATE_VALUES.get(a[field], a[field])
        m = cfg["macro"]
        m["speed"] = _MIGRATE_VALUES.get(m["speed"], m["speed"])
        return cfg

    def _save_config(self):
        self._collect_config()
        try:
            with open(CONFIG_PATH, "w", encoding="utf-8") as f:
                json.dump(self.cfg, f, indent=2, ensure_ascii=False)
        except Exception:
            pass

    def _collect_config(self):
        a = self.cfg["autoclicker"]
        a["interval_value"] = self._get_float(self.ac_interval, 100)
        a["interval_unit"] = self.ac_unit.get()
